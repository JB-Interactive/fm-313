"""Render the FM-313 screen fonts (Share Tech Mono, SIL OFL 1.1, assets/fonts) into firmware/engine/fm313_fonts.h:
4-bit anti-aliased glyphs, ASCII 32..90 (lower case folds to upper case when drawn).
  tools/gen_fonts.py"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = [  # name, file, pixel size (the phosphor screen: Share Tech Mono, SIL OFL 1.1)
    ("FM313_FONT_XS", "ShareTechMono.ttf", 11),
    ("FM313_FONT_S", "ShareTechMono.ttf", 13),
    ("FM313_FONT_M", "ShareTechMono.ttf", 19),
    ("FM313_FONT_L", "ShareTechMono.ttf", 30),
    ("FM313_FONT_XL", "ShareTechMono.ttf", 50),
]
FIRST, LAST = 32, 90

out = ["/* generated by tools/gen_fonts.py from Share Tech Mono (SIL OFL 1.1, LICENSES/OFL-1.1-ShareTechMono.txt) */",
       "#pragma once", "#include <stdint.h>", ""]
for name, fn, size in FONTS:
    font = ImageFont.truetype(str(ROOT / "assets" / "fonts" / fn), size)
    chars = [chr(c) for c in range(FIRST, LAST + 1)]
    boxes = {ch: font.getbbox(ch, anchor="ls") for ch in chars}
    top = min(b[1] for b in boxes.values())
    bot = max(b[3] for b in boxes.values())
    pad = max(0, -min(b[0] for b in boxes.values()))
    h = bot - top
    data, offs, bws, advs = [], [], [], []
    for ch in chars:
        l, t, r, b = boxes[ch]
        w = max(1, r + pad)
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((pad, -top), ch, font=font, fill=255, anchor="ls")
        bpr = (w + 1) // 2
        offs.append(len(data))
        px = img.load()
        for y in range(h):
            row = [0] * bpr
            for x in range(w):
                v = (px[x, y] * 15 + 127) // 255
                row[x // 2] |= v << (0 if x & 1 else 4)
            data.extend(row)
        bws.append(w)
        advs.append(round(font.getlength(ch)))
    p = name.lower()
    out.append(f"static const uint8_t {p}_data[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const uint8_t {p}_adv[{len(advs)}] = {{ {', '.join(map(str, advs))} }};")
    out.append(f"static const uint8_t {p}_bw[{len(bws)}] = {{ {', '.join(map(str, bws))} }};")
    out.append(f"static const uint32_t {p}_off[{len(offs)}] = {{ {', '.join(map(str, offs))} }};")
    hb = font.getbbox("H", anchor="ls")              # the capitals' ink: what centring means on this screen
    cap_y, cap_h, base = hb[1] - top, hb[3] - hb[1], -top
    out.append(f"static const fm313_font_t {name} = {{ {h}, {pad}, {FIRST}, {LAST}, {p}_adv, {p}_bw, {p}_off, {p}_data, {cap_y}, {cap_h}, {base} }};")
    out.append("")
    print(f"{name}: {size} px, cell {h} px, pad {pad}, caps {cap_y}+{cap_h}, base {base}, {len(data)} bytes")
(ROOT / "firmware" / "engine" / "fm313_fonts.h").write_text("\n".join(out) + "\n")
